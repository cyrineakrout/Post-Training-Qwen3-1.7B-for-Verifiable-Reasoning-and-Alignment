#!/usr/bin/env python3
"""
Post-process CoT JSONL files generated by generate_cot_qwen.py.

Problems this fixes:
  1. Examples with unclosed <think> blocks or missing \\boxed{} — removed
  2. Text after </think> before \\boxed{} — reconstructed as:
       <think>[reasoning]</think>\n\n\\boxed{X}
  3. System prompt normalization (optional, --normalize_system_prompt)

Usage:
  python postprocess_cot.py \
      --input general_knowledge/data/mmlu_cot_qwen3_8b.jsonl \
      --output general_knowledge/data/mmlu_cot_qwen3_8b_clean.jsonl

  # Combine multiple files:
  python postprocess_cot.py \
      --input general_knowledge/data/mmlu_cot_qwen3_8b.jsonl \
               general_knowledge/data/supergpqa_gpqa_cot_qwen3_8b.jsonl \
      --output general_knowledge/data/all_cot_qwen3_8b_clean.jsonl
"""

import argparse
import json
import re
import sys
from pathlib import Path

GENERAL_KNOWLEDGE_ROOT = Path(__file__).resolve().parents[1]

COT_SYSTEM_PROMPT = (
    "You are a careful multiple-choice general-knowledge assistant. "
    "Always show your reasoning step by step inside the <think> block before giving the final answer. "
    "Keep your reasoning concise and focused. "
    "Then finish with exactly one capital letter inside \\boxed{}. "
    "Do not answer without explicit reasoning."
)

_BOXED_RE = re.compile(r"\\boxed\{([A-T])\}", re.IGNORECASE)


def reconstruct_assistant(content: str) -> str | None:
    """
    Clean assistant content:
      - Must contain </think> and \\boxed{}
      - Strips any text between </think> and final \\boxed{X}
      - Returns: <think>...</think>\n\n\\boxed{X}
    """
    if "</think>" not in content:
        return None

    think_end = content.find("</think>")
    think_block = content[: think_end + len("</think>")]

    after_think = content[think_end + len("</think>"):]
    all_boxed = _BOXED_RE.findall(after_think)
    if not all_boxed:
        # Try full content as fallback
        all_boxed = _BOXED_RE.findall(content)
        if not all_boxed:
            return None

    answer_letter = all_boxed[-1].upper()
    return f"{think_block}\n\n\\boxed{{{answer_letter}}}"


def process_file(input_path: str, normalize_system: bool) -> tuple[list[dict], dict]:
    stats = {
        "total": 0,
        "kept": 0,
        "removed_no_think": 0,
        "removed_no_boxed": 0,
        "reconstructed": 0,
        "already_clean": 0,
    }

    rows = []
    with open(input_path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            stats["total"] += 1
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue

            messages = row.get("messages", [])
            asst_msg = next((m for m in messages if m["role"] == "assistant"), None)
            if not asst_msg:
                stats["removed_no_think"] += 1
                continue

            original = asst_msg["content"]
            cleaned = reconstruct_assistant(original)

            if cleaned is None:
                if "</think>" not in original:
                    stats["removed_no_think"] += 1
                else:
                    stats["removed_no_boxed"] += 1
                continue

            after_think = original[original.find("</think>") + len("</think>"):].strip()
            boxed_matches = _BOXED_RE.findall(after_think)
            has_extra_text = len(after_think) > (len(f"\\boxed{{{boxed_matches[-1]}}}") + 5) if boxed_matches else False

            if has_extra_text:
                stats["reconstructed"] += 1
            else:
                stats["already_clean"] += 1

            # Build clean row
            new_messages = []
            for m in messages:
                if m["role"] == "system" and normalize_system:
                    new_messages.append({"role": "system", "content": COT_SYSTEM_PROMPT})
                elif m["role"] == "assistant":
                    new_messages.append({"role": "assistant", "content": cleaned})
                else:
                    new_messages.append(m)

            new_row = {**row, "messages": new_messages}
            rows.append(new_row)
            stats["kept"] += 1

    return rows, stats


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--input", nargs="+", required=True,
        help="Input JSONL file(s). Multiple files are concatenated.",
    )
    parser.add_argument("--output", required=True, help="Output JSONL path.")
    parser.add_argument(
        "--normalize_system_prompt", action="store_true",
        help="Replace system prompt in all examples with the canonical COT_SYSTEM_PROMPT.",
    )
    args = parser.parse_args()

    all_rows = []
    total_stats = {
        "total": 0,
        "kept": 0,
        "removed_no_think": 0,
        "removed_no_boxed": 0,
        "reconstructed": 0,
        "already_clean": 0,
    }

    for input_path in args.input:
        print(f"\nProcessing: {input_path}")
        rows, stats = process_file(input_path, args.normalize_system_prompt)
        for k in total_stats:
            total_stats[k] += stats[k]
        print(f"  Total:            {stats['total']:,}")
        print(f"  Kept:             {stats['kept']:,}  ({100*stats['kept']/max(stats['total'],1):.1f}%)")
        print(f"  Removed no think: {stats['removed_no_think']:,}")
        print(f"  Removed no boxed: {stats['removed_no_boxed']:,}")
        print(f"  Reconstructed:    {stats['reconstructed']:,}  (had text after </think>)")
        print(f"  Already clean:    {stats['already_clean']:,}")
        all_rows.extend(rows)

    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        for row in all_rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

    print(f"\n{'='*60}")
    print(f"COMBINED TOTALS:")
    print(f"  Total input:      {total_stats['total']:,}")
    print(f"  Kept:             {total_stats['kept']:,}  ({100*total_stats['kept']/max(total_stats['total'],1):.1f}%)")
    print(f"  Removed no think: {total_stats['removed_no_think']:,}")
    print(f"  Removed no boxed: {total_stats['removed_no_boxed']:,}")
    print(f"  Reconstructed:    {total_stats['reconstructed']:,}")
    print(f"  Already clean:    {total_stats['already_clean']:,}")
    print(f"  Output:           {out_path}  ({len(all_rows):,} examples)")


if __name__ == "__main__":
    main()
